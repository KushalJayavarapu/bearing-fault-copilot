"""Variant E, high-uncertainty windows only: python -m rag.eval.uncertain_eval [--make-fixtures]

E: if confidence < sensor.config.HIGH_UNCERTAINTY_BELOW, retrieve with A for the top two fault types in
sensor["probabilities"] and merge (interleave, dedupe by chunk_id, top 5). Otherwise E == A.
Fixtures: every held-out 3 hp window below that threshold (--make-fixtures scans all 1534, about 2 minutes).
Labels, scoring and the request for A are the ones of rag.eval.query_eval. Writes results/uncertain_eval.md
(chunk ids and tags only). Proposal only: nothing in app/ or the rest of rag/ is touched.
"""
import json
import os
import sys
from collections import Counter
from itertools import zip_longest
from pathlib import Path

from rag.interface import get_retriever
from rag.retrieve import retrieve
from sensor.config import HIGH_UNCERTAINTY_BELOW

from .query_eval import RESULTS, derive_tags, score
from .variants import A

FIXTURES = Path(__file__).parent / "fixtures" / "high_uncertainty.json"


def make_fixtures():
    from sensor.data_loading import RECORDINGS
    from sensor.predict import list_recordings, predict
    out = []
    for r in (r for r in list_recordings() if r["held_out"]):
        for i in range(r["n_windows"]):
            s = predict(r["recording_id"], i)
            if s["confidence"] < HIGH_UNCERTAINTY_BELOW:
                out.append({"id": f"{r['recording_id']}#{i}", "true_fault": RECORDINGS[r["recording_id"]]["fault_type"], "sensor": s})
    FIXTURES.write_text("[\n" + ",\n".join(json.dumps(x) for x in out) + "\n]\n", encoding="utf-8", newline="\n")
    print(f"{len(out)} windows below {HIGH_UNCERTAINTY_BELOW} -> {FIXTURES}")


def request_for(sensor, fault):
    """A's request for another fault type on the same window (severity is the severity model's, 'none' for normal)."""
    return A({**sensor, "fault_type": fault, "severity": "none" if fault == "normal" else sensor["severity"]})


def merge(lists, k=5):
    """Interleave passage lists (first list first), drop repeated chunk ids, keep k."""
    merged, seen = [], set()
    for group in zip_longest(*lists):
        for p in group:
            if p and p["chunk_id"] not in seen:
                seen.add(p["chunk_id"])
                merged.append(p)
    return merged[:k]


def variant_e(sensor):
    top2 = sorted(sensor["probabilities"], key=sensor["probabilities"].get, reverse=True)[:2]
    return top2, merge([retrieve(request_for(sensor, f))["passages"] for f in top2])


def main():
    os.environ.pop("BEARING_RAG_MOCK", None)
    r = get_retriever()
    assert r.load() and r.index.bm25 is not None and r.index.embeddings is not None, "no real index: python -m data.fetch_guides && python -m rag.build"
    ids = {p.chunk_id for p in r.index.passages}
    tags, _ = derive_tags(r.index.passages)
    scen = json.loads(FIXTURES.read_text(encoding="utf-8"))
    tag = lambda c: ",".join(tags[c]) or "general"
    rows = []
    for s in scen:
        x = s["sensor"]
        base = retrieve(A(x))["passages"]
        top2, e = variant_e(x)
        assert all(p["chunk_id"] in ids for p in base + e), "mock fallback?"
        true_x = {**x, "fault_type": s["true_fault"]}  # score() against the TRUE fault
        rows.append({"s": s, "top2": top2, "A": base, "E": e, "A_true": score(true_x, base, tags), "E_true": score(true_x, e, tags),
                     "A_pred": score(x, base, tags), "E_pred": score(x, e, tags)})

    def agg(rs, key):
        n = len(rs)
        return (f"{sum(r[key + '_true']['hit5'] for r in rs)}/{n}", f"{sum(r[key + '_true']['right5'] for r in rs) / n:.2f}",
                f"{sum(r[key + '_pred']['right5'] for r in rs) / n:.2f}", f"{sum(r[key + '_true']['wrong5'] for r in rs) / n:.2f}",
                f"{sum(r[key + '_true']['safety'] is True for r in rs if r['s']['true_fault'] != 'normal')}/{sum(r['s']['true_fault'] != 'normal' for r in rs)}",
                "/".join(f"{sum(r[key + '_true'][k] for r in rs) / n:.1f}" for k in ("guide", "playbook", "log")))

    groups = {"all high-uncertainty": rows,
              "top-1 class is wrong": [r for r in rows if r["s"]["sensor"]["fault_type"] != r["s"]["true_fault"]],
              "top-1 class is right": [r for r in rows if r["s"]["sensor"]["fault_type"] == r["s"]["true_fault"]],
              "true fault is the 2nd class": [r for r in rows if r["top2"][1] == r["s"]["true_fault"]]}
    distinct = lambda rs, k: len({json.dumps(request_for(r["s"]["sensor"], r["s"]["sensor"]["fault_type"]) if k == "A" else r["top2"], sort_keys=True) for r in rs})
    md = ["# Variant E: top two classes when confidence is below " + str(HIGH_UNCERTAINTY_BELOW), "",
          "Generated by `python -m rag.eval.uncertain_eval`. Everything is scored against the **true** fault (the recording's), "
          "and `right5 (pred)` against the classifier's top class. Labels as in `query_eval.py`.", "",
          f"{len(rows)} held-out windows below the threshold; distinct requests: A {distinct(rows, 'A')}, E {len({tuple(r['top2']) for r in rows})} class pairs.", "",
          "| group | n | variant | true-fault passage in top 5 | true right5 | pred right5 | true wrong5 | safety step | guide/playbook/log |", "|---|---|---|---|---|---|---|---|---|"]
    for g, rs in groups.items():
        for k in ("A", "E"):
            if rs:
                a = agg(rs, k)
                md.append(f"| {g} | {len(rs)} | {k} | {a[0]} | {a[1]} | {a[2]} | {a[3]} | {a[4]} | {a[5]} |")
    lost, gained = Counter(), Counter()
    for r in rows:
        a, e = {p["chunk_id"] for p in r["A"]}, {p["chunk_id"] for p in r["E"]}
        lost.update(tag(c) for c in a - e)
        gained.update(tag(c) for c in e - a)
    md += ["", "Pushed out of the top 5 by E (tag of the passage, count over all windows): " + (", ".join(f"{k} {v}" for k, v in lost.most_common()) or "none"),
           "Brought in by E: " + (", ".join(f"{k} {v}" for k, v in gained.most_common()) or "none"), "",
           "## Window by window (true fault not already in A's top 5, or all windows if few)", "",
           "| window | true | A class (conf) | E classes | A top 5 | E top 5 |", "|---|---|---|---|---|---|"]
    for r in rows:
        s = r["s"]
        if r["E_true"]["hit5"] != r["A_true"]["hit5"] or s["id"] == "OR014@6_3#114" or len(rows) <= 12:
            fmt = lambda ps: " ".join(f"{p['chunk_id']}[{tag(p['chunk_id'])}]" for p in ps)
            md.append(f"| {s['id']} | {s['true_fault']} | {s['sensor']['fault_type']} ({s['sensor']['confidence']}) | {'+'.join(r['top2'])} | {fmt(r['A'])} | {fmt(r['E'])} |")
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "uncertain_eval.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md))


if __name__ == "__main__":
    make_fixtures() if "--make-fixtures" in sys.argv else main()
